DECLARE	@label	NVARCHAR(20)	= N'Login'
	,	@user	NVARCHAR(128)	= N'lmnReport'
	,	@msg	NVARCHAR(MAX)
	;

BEGIN TRY;
	SELECT	@msg = CONCAT(IIF(SUSER_ID(@user) IS NULL, N'CREATE', N'ALTER'), N' LOGIN [', @user, N']
	WITH PASSWORD = 0x02000BE09D4BF0DB599B3033B24EC598ADE621BB601588AE0CCA060E27BCD9B6F736BC4D16811446574D925F1C0B34B40053F24C163E52F2FFF771FF1E62C36B54FF1B2CB709 HASHED
	,	 DEFAULT_DATABASE = SabaDB
	,	 CHECK_EXPIRATION = OFF
	,	 CHECK_POLICY = OFF
	;');
	EXECUTE	master.sys.sp_executesql @msg;

	USE	SabaDB;
	SELECT	@msg	= IIF(USER_ID(@user) IS NULL
					, CONCAT(N'CREATE USER [', @user, N'] FOR LOGIN [', @user, N'];')
					, CONCAT(N'ALTER USER [', @user, N'] WITH LOGIN = [', @user, N'];')
					);
	EXECUTE	sys.sp_executesql @msg;
END TRY BEGIN CATCH;
	SELECT	@msg = N'Failed to create principle [lmnReport]';
	EXECUTE	SabaDB.logger.Error @label, @msg;
END CATCH;
GO
